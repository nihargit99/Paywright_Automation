console.log("Hello World!");
 
/* 
Console.log is an print statement in javascript. It is used to print the output to the console. In this case, 
it will print "Hello World!" to the console.

it is mostly use for-
1. Debugging: It helps developers to debug their code by printing the values of variables and 
the flow of the program.
2. Logging: It is used to log information about the program's execution, such as errors, warnings, 
and other important events.
3. Testing: It can be used to test the output of a function or a block of code by printing the results 
to the console.  
4. Learning: It is a great tool for beginners to learn and understand the basics of programming by
seeing the output of their code in real-time.
5. Performance: It can be used to measure the performance of a program by printing the time taken to execute 
a block of code or a function. 
*/

/*
Different type of console methods:
1. console.log(): It is used to print general messages to the console. 
2. console.error(): It is used to print error messages to the console.
3. console.warn(): It is used to print warning messages to the console.
4. console.info(): It is used to print informational messages to the console.
*/

console.log("Hello World!");
console.info("This is an informational message!");
console.error("This is an error message!");
console.warn("This is a warning message!");


