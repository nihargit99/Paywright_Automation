// Syntax to store the data
//     Declaration Variable= value;

// Rules to declare a variable while storing data :

    // 1. variable names must not be reserved keyword
        // e.g: let const=10;

    // 2. variable name must not be start with literals(true,false,null,etc)
        // e.g: let true="Nihar";

    // 3. Variable must not be start with a Number
        // e.g: let 1emp="Test";

    // 4. Variable must not be contains special characters except $
        // e.g.: let emp@Name="Nihar";

    // 5. Variable must not be contains space
        // e.g: let emp Name="Nihar";

    // 6. Variable must be unique
        // e.g.: empName="Nihar";


